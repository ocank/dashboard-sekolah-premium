-- ---------- Tabel ----------

create table if not exists public.school_settings (
  id int primary key,
  school_name text not null default '',
  address text not null default '',
  head_name text not null default 'Admin Kepala Sekolah',
  head_title text not null default 'Administrator Utama',
  semester text not null default 'Genap',
  academic_year text not null default 'Tahun Ajaran Aktif',
  updated_at timestamptz not null default now(),
  constraint school_settings_singleton check (id = 1)
);

create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  name text not null unique,
  room text not null default '',
  homeroom_teacher text not null default '',
  capacity int not null default 32,
  created_at timestamptz not null default now()
);

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  name text not null,
  nis text not null default '',
  class_id bigint references public.classes(id) on delete set null,
  gender text not null default 'Laki-laki',
  status text not null default 'Aktif',
  created_at timestamptz not null default now()
);
create unique index if not exists students_nis_unique
  on public.students (nis) where nis <> '';

create table if not exists public.teachers (
  id bigint generated by default as identity primary key,
  name text not null,
  subject text not null default '',
  status text not null default 'Aktif',
  created_at timestamptz not null default now()
);

create table if not exists public.journals (
  id bigint generated by default as identity primary key,
  date date not null default current_date,
  class_id bigint references public.classes(id) on delete set null,
  subject text not null default '',
  material text not null default '',
  activity text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.att_sessions (
  id bigint generated by default as identity primary key,
  date date not null,
  class_id bigint references public.classes(id) on delete cascade,
  session_label text not null default 'Sesi 1',
  created_at timestamptz not null default now(),
  unique (date, class_id, session_label)
);

create table if not exists public.att_records (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.att_sessions(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete cascade,
  status text not null check (status in ('H','S','I','A')),
  unique (session_id, student_id)
);

create table if not exists public.grades (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  subject text not null,
  score numeric not null check (score >= 0 and score <= 100),
  unique (student_id, subject)
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  message text not null default '',
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

-- ---------- Row Level Security ----------
-- Semua tabel: hanya user yang sudah LOGIN (authenticated) yang
-- boleh membaca/menulis. Anon / publik TIDAK bisa membaca data siswa.

alter table public.school_settings enable row level security;
alter table public.classes enable row level security;
alter table public.students enable row level security;
alter table public.teachers enable row level security;
alter table public.journals enable row level security;
alter table public.att_sessions enable row level security;
alter table public.att_records enable row level security;
alter table public.grades enable row level security;
alter table public.notifications enable row level security;

do $$
declare t text;
begin
  foreach t in array array[
    'school_settings','classes','students','teachers','journals',
    'att_sessions','att_records','grades','notifications'
  ] loop
    execute format('drop policy if exists "authenticated full access" on public.%I', t);
    execute format(
      'create policy "authenticated full access" on public.%I
         for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

